/**
 * The generated dialogue map must stay complete and in step with the source.
 * This guards the documentation artifact itself: if a topic, question or
 * condition stops being documented, the check fails.
 */
import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync, existsSync } from "node:fs";

import { TOPICS } from "../src/dialogue-topics.ts";
import { SENTENCE_LIBRARY } from "../src/sentence-library.ts";

const pageUrl = new URL("../docs/dialogue-map.html", import.meta.url);
const generatorUrl = new URL("../tools/dialogue-map.mjs", import.meta.url);

test("the dialogue map page and its generator exist", () => {
  assert.ok(existsSync(pageUrl), "docs/dialogue-map.html is missing (run: npm run dialogue-map)");
  assert.ok(existsSync(generatorUrl), "tools/dialogue-map.mjs is missing");
});

const html = readFileSync(pageUrl, "utf8");

test("the page documents every topic, question and answer variant", () => {
  const totalQuestions = TOPICS.reduce((sum, topic) => sum + topic.asks.length, 0);
  const totalVariants = TOPICS.reduce((sum, topic) => sum + topic.variants.length, 0);

  assert.equal((html.match(/class="topic"/g) ?? []).length, TOPICS.length, "topic card count drifted");
  assert.equal((html.match(/class="question"/g) ?? []).length, totalQuestions, "question count drifted");
  assert.equal((html.match(/class="variant"/g) ?? []).length, totalVariants, "answer-variant count drifted");
});

test("every answer text in the source appears verbatim in the page", () => {
  const escape = (value: string) =>
    value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");
  for (const topic of TOPICS) {
    for (const variant of topic.variants) {
      assert.ok(html.includes(escape(variant.text)), `missing answer from ${topic.id}: ${variant.text.slice(0, 48)}…`);
      if (variant.cause) {
        assert.ok(html.includes(escape(variant.cause)), `missing cause from ${topic.id}: ${variant.cause.slice(0, 48)}…`);
      }
    }
  }
});

test("every condition is shown as a badge", () => {
  for (const topic of TOPICS) {
    for (const variant of topic.variants) {
      if (!variant.when) {
        assert.ok(html.includes("badge-default"), "fallback variant has no fallback badge");
        continue;
      }
      for (const [key, value] of Object.entries(variant.when)) {
        assert.ok(html.includes(`data-cond="${key}"`), `condition key "${key}" from ${topic.id} is not shown`);
        assert.ok(html.includes(`= ${value}<`), `condition value "${key}=${value}" from ${topic.id} is not shown`);
      }
    }
  }
});

test("the follow-up graph is drawn for both directions", () => {
  let edges = 0;
  for (const topic of TOPICS) {
    for (const next of topic.followUps) {
      assert.ok(html.includes(`href="#topic-${next}"`), `missing follow-up arrow ${topic.id} -> ${next}`);
      edges += 1;
    }
  }
  assert.ok(edges > 60, `expected a rich follow-up graph, found ${edges} edges`);
});

test("the page documents meta questions and follow-up intents too", () => {
  for (const entry of SENTENCE_LIBRARY) {
    if (entry.intent === "query.topic") continue;
    assert.ok(html.includes(entry.id), `entry "${entry.id}" is not documented`);
  }
});

test("the page is self-contained and carries no external asset references", () => {
  assert.doesNotMatch(html, /<script[^>]+src=/i, "no external scripts allowed");
  assert.doesNotMatch(html, /<link[^>]+href="(?:https?:)?\/\//i, "no external stylesheets allowed");
  assert.match(html, /<style>/, "styles must be inline");
  assert.match(html, /Generated by: npm run dialogue-map/, "generated-file banner missing");
  assert.ok(html.length > 100_000, `page looks truncated (${html.length} bytes)`);
});
